/**
 * Describes where the orbital / fleet data came from.
 *   simulated — static reference values from orbital-simulation.ts (no external call)
 *   n2yo      — real-time positions from the N2YO API (ORBITAL_DATA_MODE=live)
 *   fallback  — live mode was requested but the N2YO call failed; simulation used instead
 *   live      — alias retained for dashboard/telemetry pipeline compatibility
 */
export type DataSourceMode = 'live' | 'simulated' | 'n2yo' | 'fallback' | 'mixed' | 'iss-live';

export interface SpaceDataProviderState {
  isLoading: boolean;
  error: string | null;
  dataSource: DataSourceMode;
  lastUpdated: string | null;
}

// ── Orbital / N2YO position data ──────────────────────────────────────────────

/**
 * Real-time orbital position for a tracked object.
 * Sourced from N2YO when live mode is active; not derived from simulated telemetry.
 */
export interface OrbitalPosition {
  /** NORAD catalog number */
  norad_id: number;
  /** Satellite/object name from TLE database */
  name: string;
  /** Latitude in decimal degrees (-90 to +90) */
  latitude: number;
  /** Longitude in decimal degrees (-180 to +180) */
  longitude: number;
  /** Altitude above mean sea level (km) */
  altitude_km: number;
  /** Ground-track velocity (km/s) */
  velocity_km_s: number;
  /** Timestamp of this position fix (ISO 8601) */
  timestamp: string;
  /** Visibility category: 'daylight' | 'eclipsed' | 'visible' | 'unknown' */
  visibility: 'daylight' | 'eclipsed' | 'visible' | 'unknown';
  /** Inclination of the orbit (degrees) */
  inclination_deg?: number;
  /** Orbital period (minutes) */
  period_min?: number;
  /** Number of revolutions since epoch */
  revs_at_epoch?: number;
  /** True if position was read from live N2YO API */
  is_live: boolean;
}

/** Top-level response shape returned by /api/orbital */
export interface OrbitalDataResponse {
  positions: OrbitalPosition[];
  data_source: DataSourceMode;
  /** ISO timestamp of the most recent API fetch */
  fetched_at: string;
  /** Human-readable note, e.g. fallback reason */
  note?: string;
  error?: string;
}

